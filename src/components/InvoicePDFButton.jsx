import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { Download } from "lucide-react";

const InvoicePDFButton = ({ invoice }) => {
  const downloadInvoicePDF = () => {
    const doc = new jsPDF();

    // =========================
    // Company Header
    // =========================
    doc.setFontSize(20);
    doc.setFont("helvetica", "bold");
    doc.text("BillPro", 14, 20);

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.text("Billing Management System", 14, 27);
    doc.text("Tirupati, Andhra Pradesh, India", 14, 33);

    // =========================
    // Invoice Title
    // =========================
    doc.setFontSize(18);
    doc.setFont("helvetica", "bold");
    doc.text("INVOICE", 150, 20);

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");

    doc.text(
      `Invoice No: ${invoice.invoiceNumber}`,
      150,
      27
    );

    doc.text(
      `Date: ${new Date(invoice.createdAt).toLocaleDateString("en-IN")}`,
      150,
      33
    );

    // =========================
    // Line
    // =========================
    doc.line(14, 40, 196, 40);

    // =========================
    // Customer Information
    // =========================
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("Bill To", 14, 52);

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");

    doc.text(
      `Name: ${invoice.customerName || "N/A"}`,
      14,
      60
    );

    doc.text(
      `Phone: ${invoice.customerPhone || "N/A"}`,
      14,
      67
    );

    // =========================
    // Items Table
    // =========================
    const tableData = (invoice.items || []).map(
      (item, index) => [
        index + 1,
        item.productName,
        item.quantity,
        `Rs. ${Number(item.price || 0).toLocaleString("en-IN")}`,
        `Rs. ${Number(item.total || 0).toLocaleString("en-IN")}`,
      ]
    );

    autoTable(doc, {
      startY: 78,

      head: [
        [
          "#",
          "Product",
          "Quantity",
          "Price",
          "Total",
        ],
      ],

      body: tableData,

      theme: "grid",

      styles: {
        fontSize: 9,
        cellPadding: 4,
      },

      headStyles: {
        fontStyle: "bold",
      },
    });

    // =========================
    // Summary
    // =========================
    const finalY =
      doc.lastAutoTable.finalY + 10;

    const subtotal = Number(invoice.subtotal || 0);
    const discount = Number(invoice.discount || 0);
    const gst = Number(invoice.gst || 0);
    const gstAmount = Number(invoice.gstAmount || 0);
    const grandTotal = Number(invoice.grandTotal || 0);

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");

    doc.text(
      `Subtotal: Rs. ${subtotal.toLocaleString("en-IN")}`,
      135,
      finalY
    );

    doc.text(
      `Discount: Rs. ${discount.toLocaleString("en-IN")}`,
      135,
      finalY + 7
    );

    doc.text(
      `GST (${gst}%): Rs. ${gstAmount.toLocaleString("en-IN")}`,
      135,
      finalY + 14
    );

    // =========================
    // Grand Total
    // =========================
    doc.setFontSize(13);
    doc.setFont("helvetica", "bold");

    doc.text(
      `Grand Total: Rs. ${grandTotal.toLocaleString("en-IN")}`,
      135,
      finalY + 25
    );

    // =========================
    // Footer
    // =========================
    doc.setFontSize(9);
    doc.setFont("helvetica", "normal");

    doc.text(
      "Thank you for your business!",
      14,
      285
    );

    doc.text(
      "Generated by BillPro Billing System",
      14,
      291
    );

    // =========================
    // Download
    // =========================
    doc.save(
      `${invoice.invoiceNumber}.pdf`
    );
  };

  return (
    <button
      onClick={downloadInvoicePDF}
      className="inline-flex items-center gap-2 rounded-lg bg-blue-600 px-3 py-2 text-sm font-medium text-white hover:bg-blue-700"
    >
      <Download size={16} />

      Invoice
    </button>
  );
};

export default InvoicePDFButton;